def main() -> None:
    clf = Classifier()
    fails = []
    for title, body, expect_drop, note in CASES:
        v = clf.classify(title, body)
        if v.drop != expect_drop:
            fails.append((title, expect_drop, v.drop, v.category, v.matched, note))

    total = len(CASES)
    print(f"回归用例 {total} 条")
    if not fails:
        print(f"全部通过 ✓  （保留 {sum(1 for c in CASES if not c[2])} / 剔除 {sum(1 for c in CASES if c[2])}）")
        return

    print(f"失败 {len(fails)} 条：")
    for t, exp, got, cat, kw, note in fails:
        print(f"  ✗ {t}")
        print(f"      期望 {'剔除' if exp else '保留'}，实际 {'剔除' if got else '保留'}"
              f"{f'（{cat}｜{kw}）' if got else ''}")
        print(f"      说明：{note}")
    sys.exit(1)


if __name__ == "__main__":
    main()
